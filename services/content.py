# ── Ранги по средней точности ─────────────────────────────────────────────────

RANKS = [
    (0, 60, "Студент"),
    (60, 70, "Ординатор"),
    (70, 80, "Кардиолог"),
    (80, 90, "Заведующий отделением"),
    (90, 101, "Министр кардиологии"),
]

RANKS_TEXT = (
    "<b>Ранги</b>\n"
    "• Студент — 0–60%\n"
    "• Ординатор — 60–70%\n"
    "• Кардиолог — 70–80%\n"
    "• Заведующий отделением — 80–90%\n"
    "• Министр кардиологии — 90–100%"
)


def get_rank(accuracy_pct: float) -> str:
    """Возвращает название ранга по средней точности (в процентах)."""
    for low, high, name in RANKS:
        if low <= accuracy_pct < high:
            return name
    return RANKS[-1][2]
